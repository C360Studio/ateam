func loadReportSnapshot(ctx context.Context, path string) (reportSnapshot, error) {
	var snapshot reportSnapshot
	if err := ctx.Err(); err != nil {
		return snapshot, err
	}
	f, err := os.OpenFile(path, os.O_RDONLY|bundleReadFlags, 0)
	if err != nil {
		return snapshot, fmt.Errorf("open report input: %w", err)
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return snapshot, err
	}
	if !info.Mode().IsRegular() {
		return snapshot, fmt.Errorf("report input must be a regular file")
	}
	data, err := readBounded(f, maxExperimentArtifactBytes)
	if err != nil {
		return snapshot, fmt.Errorf("read report input: %w", err)
	}
	if err := ctx.Err(); err != nil {
		return snapshot, err
	}
	run, err := parseExperimentRun(data)
	if err != nil {
		return snapshot, fmt.Errorf("validate report input: %w", err)
	}
	return reportSnapshot{Run: run, FileSHA: digest(data)}, nil
}

func experimentReportFiles(ctx context.Context, path, replayPath string) (map[string][]byte, error) {
	original, err := loadReportSnapshot(ctx, path)
	if err != nil {
		return nil, err
	}
	var replay *reportSnapshot
	if replayPath != "" {
		value, err := loadReportSnapshot(ctx, replayPath)
		if err != nil {
			return nil, err
		}
		replay = &value
	}
	report, err := projectExperimentReport(original.Run, replay)
	if err != nil {
		return nil, err
	}
	results, err := reportJSON(report)
	if err != nil {
		return nil, err
	}
	markdown := []byte(formatExperimentReport(report))
	evidence := reportEvidence{ExporterSourceSHA: reportSourceDigest(), ExporterSourceScope: "report.go, report_markdown.go, report_files.go; library implementation only, not a whole-binary or transitive dependency attestation", Kind: "ateam.benchmark-report-evidence", Version: reportVersion,
		Original:     reportEvidenceRef{FileSHA: original.FileSHA, RunSHA: original.Run.Digest},
		Files:        map[string]string{"results.json": digest(results), "results.md": digest(markdown)},
		Availability: "Original and replay artifacts are not included; rederivation requires separately retained originals and the matching evaluator version.",
		Limitation:   "Hashes detect changes, not authorship or independent execution. Review metadata before publication; field omission is not universal secret scrubbing."}
	if replay != nil {
		evidence.Replay = &reportEvidenceRef{FileSHA: replay.FileSHA, RunSHA: replay.Run.Digest}
	}
	manifest, err := reportJSON(evidence)
	if err != nil {
		return nil, err
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	return map[string][]byte{"results.json": results, "results.md": markdown, "evidence.json": manifest}, nil
}

func reportJSON(value any) ([]byte, error) {
	data, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

func projectExperimentReport(run ExperimentRun, replay *reportSnapshot) (experimentReport, error) {
	var report experimentReport
	comparison, err := CompareExperiment(run)
	if err != nil {
		return report, err
	}
	replayResult, err := associateReportReplay(run, replay)
	if err != nil {
		return report, err
	}
	r, e := run.Resolved, run.Resolved.Experiment
	identity := reportIdentity{Name: e.Name, Agent: e.Agent, AgentVersion: e.AgentVersion, Model: e.Model, Runtime: r.Runtime,
		NativeVersion: r.GeminiVersion + r.ClaudeVersion + r.CodexVersion, BridgeVersion: r.MercuryBridgeVersion,
		ConfigSHA: r.ConfigSHA, BaselineSHA: digest([]byte(e.Baseline)), CandidateSHA: digest([]byte(e.Candidate)),
		RunnerSHA: r.RunnerSHA, EvaluatorSHA: r.EvaluatorSHA, GoDriverSHA: r.Grader.SHA, GoDriverVersion: r.Grader.Version,
		CommandFileSHAs: []string{}, Tasks: e.Tasks, Repetitions: e.Repetitions, Seed: e.Seed, TimeoutSeconds: e.TimeoutSeconds,
		MaxRunSeconds: e.MaxRunSeconds, MaxTotalTokens: e.MaxTotalTokens, BudgetPolicy: r.BudgetPolicy}
	for _, sha := range r.CommandFiles {
		identity.CommandFileSHAs = append(identity.CommandFileSHAs, sha)
	}
	sort.Strings(identity.CommandFileSHAs)
	if e.IsNative() {
		identity.NativeSettingsSHA = jsonDigest(r.NativeSettings)
		identity.NativeArgumentsSHA = jsonDigest(r.NativeArguments)
	}
	report = experimentReport{Kind: "ateam.benchmark-report", Version: reportVersion, RecordedAt: run.Created,
		Identity: identity, Schedule: r.Schedule, Comparison: comparison, Accounting: summarizeUsageAccounting(run.Attempts),
		Attempts: []reportAttempt{}, Pairs: []reportPair{}, Replay: replayResult,
		Counts: reportCounts{Scheduled: len(r.Schedule), Retained: len(run.Attempts), Unstarted: len(r.Schedule) - len(run.Attempts)}}
	report.Accounting.Basis = "adapter-reported"
	if e.IsNative() {
		report.Accounting.Basis = "native-cli-reported"
	}
	if isMercury(e) {
		report.Accounting.Basis = "captured-provider-wire"
	}
	for i, a := range run.Attempts {
		row := reportAttempt{Index: i, Trial: a.Request.Trial, Status: a.Status, AgentNanos: a.AgentNanos, GradeNanos: a.GradeNanos, SourceSHA: a.SourceSHA}
		if a.Status == "passed" || a.Status == "failed" {
			pass := a.Status == "passed"
			row.Passed = &pass
			report.Counts.Graded++
			if pass {
				report.Counts.Passed++
			} else {
				report.Counts.Failed++
			}
		} else {
			report.Counts.Unevaluable++
		}
		if a.Response != nil && a.Response.Usage != nil {
			u := a.Response.Usage
			row.Usage = &reportUsage{Input: u.InputTokens, Output: u.OutputTokens, Cached: u.CachedInputTokens, Reasoning: u.ReasoningOutputTokens}
		}
		report.Attempts = append(report.Attempts, row)
	}
	for i := 0; i+1 < len(report.Attempts); i += 2 {
		a, b := report.Attempts[i], report.Attempts[i+1]
		if a.Trial.Arm == "candidate" {
			a, b = b, a
		}
		pair := reportPair{Baseline: a.Index, Candidate: b.Index, QualityEligible: a.Passed != nil && b.Passed != nil}
		if a.Status == "passed" && b.Status == "passed" {
			delta := b.AgentNanos - a.AgentNanos
			pair.TimeDelta = &delta
		}
		if a.Usage != nil && b.Usage != nil {
			delta := b.Usage.Input + b.Usage.Output - a.Usage.Input - a.Usage.Output
			pair.TokenDelta = &delta
		}
		report.Pairs = append(report.Pairs, pair)
	}
	return report, nil
}

func associateReportReplay(original ExperimentRun, replay *reportSnapshot) (reportReplay, error) {
	result := reportReplay{State: "not-provided", ChangedAttempts: []int{}}
	if replay == nil {
		return result, nil
	}
	if err := validateRun(replay.Run); err != nil {
		return result, fmt.Errorf("invalid replay: %w", err)
	}
	if replayExecutionDigest(original) != replayExecutionDigest(replay.Run) {
		return result, fmt.Errorf("replay execution identity differs from original")
	}
	result.State = "matched"
	for i, a := range original.Attempts {
		b := replay.Run.Attempts[i]
		if a.Status != b.Status || a.Grade.Supported != b.Grade.Supported || a.Grade.Passed != b.Grade.Passed || a.Grade.Verdict != b.Grade.Verdict {
			result.State = "different-results"
			result.ChangedAttempts = append(result.ChangedAttempts, i)
		}
	}
	return result, nil
}

func replayExecutionDigest(run ExperimentRun) string {
	run.Created = time.Time{}
	run.Digest = ""
	run.Attempts = append([]Attempt(nil), run.Attempts...)
	for i := range run.Attempts {
		a := &run.Attempts[i]
		if a.Status == "passed" || a.Status == "failed" || a.Status == "grading-error" {
			a.Status = "gradable"
			a.Grade = CandidateEvaluation{}
			a.GradeNanos = 0
			a.Diagnostic = ""
		}
	}
	return jsonDigest(run)
}
