const reportVersion = 1

//go:embed report.go report_markdown.go report_files.go
var reportSources embed.FS

func reportSourceDigest() string {
	var source strings.Builder
	for _, name := range []string{"report.go", "report_markdown.go", "report_files.go"} {
		data, _ := reportSources.ReadFile(name)
		source.WriteString(name)
		source.Write(data)
	}
	return digest([]byte(source.String()))
}

// ExportExperimentReport publishes validated offline facts into a new directory.
// It never invokes adapters, graders, version probes, or publication services.
func ExportExperimentReport(ctx context.Context, runPath, replayPath, outputDir string) error {
	files, err := experimentReportFiles(ctx, runPath, replayPath)
	if err != nil {
		return err
	}
	return writeReportFiles(ctx, outputDir, files)
}

// CheckExperimentReport checks generated bytes without writing any files.
func CheckExperimentReport(ctx context.Context, runPath, replayPath, outputDir string) error {
	files, err := experimentReportFiles(ctx, runPath, replayPath)
	if err != nil {
		return err
	}
	return checkReportFiles(ctx, outputDir, files)
}

